/// 把一条 [Plain] 渲染成"**术语**:白话(趣味)"。
String renderPlain(Plain p, {bool bold = true}) =>
    '${bold ? '**${p.term}**' : p.term}:${p.plain}${p.fun.isEmpty ? '' : ' ${p.fun}'}';

/// 渲染成两行的卡片式条目。
String renderPlainLines(Plain p) => '- **${p.term}** — ${p.plain}\n  > ${p.fun}';
