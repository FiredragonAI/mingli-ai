  static Map<String, List<MapEntry<String, String>>> _phraseIndex = {};

  static void loadFromJson(String jsonText) {
    final raw = jsonDecode(jsonText) as Map<String, dynamic>;
    _chars = {for (final e in raw.entries) e.key: e.value as String};
    _chars.addAll(charOverrides);
    _buildPhraseIndex();
  }

  /// 没有字表时也能用(只做词级修正 + 人工裁定的单字),测试环境靠它。
  static void ensureMinimal() {
    if (_chars.isEmpty) {
      _chars = Map.of(charOverrides);
      _buildPhraseIndex();
    }
  }

  static void _buildPhraseIndex() {
    _phraseIndex = {};
    for (final e in phraseOverrides.entries) {
      _phraseIndex.putIfAbsent(e.key[0], () => []).add(e);
    }
    for (final list in _phraseIndex.values) {
      list.sort((a, b) => b.key.length.compareTo(a.key.length));
    }
  }

  /// 简体 → 繁体。非中文字符原样返回。
  static String convert(String s) {
    if (s.isEmpty) return s;
    if (_phraseIndex.isEmpty) ensureMinimal();
    final buf = StringBuffer();
    var i = 0;
    while (i < s.length) {
      final ch = s[i];
      final candidates = _phraseIndex[ch];
      if (candidates != null) {
        var matched = false;
        for (final e in candidates) {
          if (s.startsWith(e.key, i)) {
            buf.write(e.value);
            i += e.key.length;
            matched = true;
            break;
          }
        }
        if (matched) continue;
      }
      buf.write(_chars[ch] ?? ch);
      i++;
    }
    return buf.toString();
  }
