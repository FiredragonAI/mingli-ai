export function systemPrompt(kind: Kind): string {
  return `${BASE}\n\n${PER_KIND[kind]}`;
}

/** 用户消息:把 payload 原样给模型,并点明各部分是什么。 */
export function userMessage(kind: Kind, payload: Record<string, unknown>): string {
  const parts: string[] = [];
  for (const [key, value] of Object.entries(payload)) {
    if (value === null || value === undefined) continue;
    parts.push(`### ${labelOf(key)}\n\`\`\`json\n${JSON.stringify(value, null, 1)}\n\`\`\``);
  }
  const focus = typeof payload.focus === "string" ? `\n\n用户特别关心:${payload.focus}` : "";
  return `以下是已推算完成的数据,请按系统要求解读(任务类型:${kind})。${focus}\n\n${parts.join("\n\n")}`;
}

function labelOf(key: string): string {
  switch (key) {
    case "chart":
      return "命盘(八字)";
    case "fortune":
      return "今日运势分析";
    case "marriage":
      return "合婚分析";
    case "name":
      return "姓名分析";
    case "almanac":
      return "黄历";
    case "features":
      return "影像几何特征";
    case "zodiac":
      return "星座档案";
    case "match":
      return "星座配对";
    default:
      return key;
  }
}
